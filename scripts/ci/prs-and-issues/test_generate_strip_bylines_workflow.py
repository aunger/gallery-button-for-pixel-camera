#!/usr/bin/env python3
"""Tests for generate_strip_bylines_workflow.py.

The first test is the parity check: it fails whenever the copy of the strip
script in .github/workflows/strip-session-bylines.yml differs from what the
generator would write from the modules in this directory.
"""

import json
import os
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

import yaml
from generate_strip_bylines_workflow import (
    BEGIN,
    END,
    MODULES,
    WORKFLOW,
    generate,
    main,
    script,
)


def _strip_step() -> dict:
    with open(WORKFLOW, encoding="utf-8") as f:
        steps = yaml.safe_load(f)["jobs"]["strip-bylines"]["steps"]
    return next(step for step in steps if BEGIN in step.get("run", ""))


class WorkflowParityTest(unittest.TestCase):
    """The workflow holds exactly what the generator would write, and it runs."""

    def test_workflow_is_up_to_date(self):
        self.assertEqual(
            0,
            main(["--check"]),
            "run scripts/ci/prs-and-issues/generate_strip_bylines_workflow.py",
        )

    def test_step_runs_the_script_with_python(self):
        # Without this, bash would run the Python text and fail on every event.
        self.assertEqual("python3 {0}", _strip_step().get("shell"))

    def test_generated_step_runs(self):
        # A body with no byline makes no API call, so this runs the whole
        # generated script offline: every module's top level, and the
        # handler's call into session_bylines.
        with tempfile.TemporaryDirectory() as d:
            script_path = os.path.join(d, "step.py")
            event_path = os.path.join(d, "event.json")
            with open(script_path, "w", encoding="utf-8") as f:
                f.write(_strip_step()["run"])
            with open(event_path, "w", encoding="utf-8") as f:
                json.dump({"comment": {"id": 1, "body": "no byline here"}}, f)
            env = {
                **os.environ,
                "GITHUB_TOKEN": "unused",
                "GITHUB_REPOSITORY": "owner/repo",
                "GITHUB_EVENT_NAME": "issue_comment",
                "GITHUB_EVENT_PATH": event_path,
            }
            result = subprocess.run(
                [sys.executable, script_path],
                check=False,
                env=env,
                capture_output=True,
                text=True,
                cwd=d,
            )
        self.assertEqual(0, result.returncode, result.stderr)
        self.assertIn("no bylines found", result.stdout)

    def test_generated_step_sends_the_stripped_body(self):
        # The path past the early return: the generated copy's handler, its
        # call into github_headers, and the request it makes.
        namespace = {"__name__": "generated_step"}
        exec(compile(_strip_step()["run"], "step", "exec"), namespace)  # noqa: S102
        fake = mock.Mock()
        namespace["requests"] = fake
        payload = {
            "comment": {
                "id": 7,
                "body": "hi\n---\n_Generated by [Claude Code](https://claude.ai/code)_",
            }
        }
        self.assertTrue(namespace["handle_issue_comment"]("tok", "owner/repo", payload))
        fake.patch.assert_called_once()
        args, kwargs = fake.patch.call_args
        self.assertEqual(("https://api.github.com/repos/owner/repo/issues/comments/7",), args)
        self.assertEqual({"body": "hi"}, kwargs["json"])
        self.assertEqual("Bearer tok", kwargs["headers"]["Authorization"])


class ScriptTest(unittest.TestCase):
    """What the generator copies, and what it refuses to copy."""

    def _modules(self, d: str, **sources: str) -> str:
        defaults = {
            "github_headers": '"""Doc."""\n\n\ndef github_headers(token):\n    return {}\n',
            "session_bylines": '"""Doc."""\n\n\ndef strip_bylines(text):\n    return text\n',
            "strip_session_bylines": (
                '#!/usr/bin/env python3\n"""Doc."""\n\n'
                "from session_bylines import strip_bylines\n\n\n"
                "def main():\n    return 0\n"
            ),
        }
        defaults.update(sources)
        for name in MODULES:
            with open(os.path.join(d, name + ".py"), "w", encoding="utf-8") as f:
                f.write(defaults[name])
        return d

    def test_real_modules_lose_shebangs_docstrings_and_sibling_imports(self):
        code = script()
        self.assertNotIn("from github_headers import", code)
        self.assertNotIn("from session_bylines import", code)
        self.assertNotIn("#!", code)
        self.assertNotIn("session_bylines.py: Recognize", code)
        self.assertLess(code.index("def github_headers("), code.index("def strip_bylines("))
        self.assertLess(code.index("def strip_bylines("), code.index("def main("))

    def test_each_module_is_headed_by_its_file_name(self):
        with tempfile.TemporaryDirectory() as d:
            code = script(self._modules(d))
        self.assertTrue(code.startswith("# --- github_headers.py ---\ndef github_headers("))
        self.assertIn("# --- strip_session_bylines.py ---\ndef main():", code)

    def test_a_shebang_like_line_inside_a_string_is_kept(self):
        body = '"""Doc."""\n\n\nEXAMPLE = """\n#!/bin/sh\n"""\n\n\ndef strip_bylines(text):\n    return text\n'
        with tempfile.TemporaryDirectory() as d:
            code = script(self._modules(d, session_bylines=body))
        self.assertIn("\n#!/bin/sh\n", code)

    def test_an_import_it_cannot_copy_is_refused(self):
        imports = (
            "import session_bylines",
            "from session_bylines import strip_bylines as sb",
            "from session_bylines import (\n    strip_bylines,\n)",
        )
        for line in imports:
            source = f'"""Doc."""\n\n{line}\n\n\ndef main():\n    return 0\n'
            with self.subTest(line=line), tempfile.TemporaryDirectory() as d:
                with self.assertRaisesRegex(ValueError, "cannot copy this import"):
                    script(self._modules(d, strip_session_bylines=source))

    def test_a_name_defined_twice_is_refused(self):
        twice = '"""Doc."""\n\n\ndef main():\n    return 1\n\n\ndef strip_bylines(text):\n    return text\n'
        with tempfile.TemporaryDirectory() as d:
            with self.assertRaisesRegex(ValueError, "'main' is defined in both"):
                script(self._modules(d, session_bylines=twice))

    def test_a_workflow_expression_is_refused(self):
        source = '"""Doc."""\n\nREPO = "${{ github.repository }}"\n\n\ndef strip_bylines(t):\n    return t\n'
        with tempfile.TemporaryDirectory() as d:
            with self.assertRaisesRegex(ValueError, "evaluate"):
                script(self._modules(d, session_bylines=source))


class GenerateTest(unittest.TestCase):
    WORKFLOW_TEXT = f"before\n    {BEGIN}\n    old line\n    {END}\nafter\n"

    def test_region_is_replaced_and_indented(self):
        self.assertEqual(
            f"before\n    {BEGIN}\n    x = 1\n\n    y = 2\n    {END}\nafter\n",
            generate(self.WORKFLOW_TEXT, "x = 1\n\ny = 2\n"),
        )

    def test_trailing_whitespace_is_kept(self):
        generated = generate(self.WORKFLOW_TEXT, 's = """a  \nb"""\n')
        self.assertIn('\n    s = """a  \n    b"""\n', generated)

    def test_missing_marker_is_reported(self):
        for text in (f"{BEGIN}\n", f"{END}\n", "neither\n"):
            with self.subTest(text=text), self.assertRaises(ValueError):
                generate(text, "x = 1\n")

    def test_repeated_marker_is_reported(self):
        with self.assertRaises(ValueError):
            generate(self.WORKFLOW_TEXT + f"{BEGIN}\n", "x = 1\n")

    def test_reversed_markers_are_reported(self):
        with self.assertRaises(ValueError):
            generate(f"{END}\n{BEGIN}\n", "x = 1\n")


if __name__ == "__main__":
    unittest.main()
